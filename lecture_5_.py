"""---
# Section 2: Summary Statistics (10 min)

Summary statistics describe a whole column with just a few numbers.

- **Centre**: mean, median, mode (where is the "middle"?)
- **Spread**: min, max, standard deviation, quartiles (how far apart are the values?)
- **Shape**: is the data balanced or stretched to one side? (compare mean and median)

> 🎯 **Business problem(s) solved:** **BP1** (revenue level), **BP4** (outliers show up as mean vs median), **BP5** (payment share).

### 📖 Definitions
| Term | Definition | Zomato example |
|---|---|---|
| **Summary statistics** | A few numbers that describe a whole column. | Mean, median, std |
| **Mean** | Sum of all values ÷ number of values. Affected by very large/small values. | Average order amount |
| **Median** | The middle value when sorted. Not affected much by extremes. | Typical order amount |
| **Mode** | The most frequent value. | Most common cuisine |
| **Minimum / Maximum** | Smallest / largest value. | Cheapest / biggest order |
| **Range** | Maximum − Minimum. | Spread of order amounts |
| **Standard deviation** | Average distance of values from the mean. Large = very spread out. | Order amounts vary by ~Rs 460 |
| **Quartiles (Q1, Q2, Q3)** | Values that split sorted data into 4 equal parts (25%, 50%, 75%). | Q3 = 75% of orders are below this |
| **IQR** | Interquartile Range = Q3 − Q1. The spread of the middle 50%. | Used to find outliers |
| **Skewness** | When data stretches to one side. Mean > median means right-skewed. | A few big orders |
| **`value_counts()`** | Counts how often each category appears. | Orders per city |
"""

# 2.1  describe(): one command, many statistics (numerical columns)
df[number_cols].describe().round(2)

# 2.2  Statistics for one important column: Final_Amount (what the customer paid)
amount = df["Final_Amount"]

print("Mean (average)      : Rs", round(amount.mean(), 2))
print("Median (middle)     : Rs", amount.median())
print("Mode (most common)  : Rs", amount.mode()[0])
print("Minimum             : Rs", amount.min())
print("Maximum             : Rs", amount.max())
print("Standard deviation  : Rs", round(amount.std(), 2))
print("Range (max - min)   : Rs", amount.max() - amount.min())

# 2.3  Mean vs Median: what does the gap tell us?
mean_value   = amount.mean()
median_value = amount.median()
print(f"Mean   = Rs {mean_value:,.2f}")
print(f"Median = Rs {median_value:,.2f}")

if mean_value > median_value:
    print("Mean is higher than median -> a few very large orders pull the average UP (right-skewed).")
else:
    print("Mean is close to or lower than median -> no strong pull from large orders.")

